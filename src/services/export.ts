import { UnifiedDocument, VectorShape } from '../types/creativeSuite';

/**
 * Generates pristine SVG XML code from vector shapes.
 */
export function buildRawSvg(doc: UnifiedDocument): string {
  const shapesXml = doc.vectorLayers
    .map((s) => {
      if (s.type === 'shield') {
        const cx = s.x + s.width / 2;
        const cy = s.y + s.height;
        const d = `M ${s.x} ${s.y} L ${s.x + s.width} ${s.y} C ${s.x + s.width} ${s.y + s.height * 0.65} ${cx} ${cy} ${cx} ${cy} C ${cx} ${cy} ${s.x} ${s.y + s.height * 0.65} ${s.x} ${s.y} Z`;
        return `  <path d="${d}" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${s.strokeWidth}" opacity="${s.opacity}" />`;
      }
      if (s.type === 'rect') {
        return `  <rect x="${s.x}" y="${s.y}" width="${s.width}" height="${s.height}" rx="6" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${s.strokeWidth}" opacity="${s.opacity}" transform="rotate(${s.rotation} ${s.x + s.width / 2} ${s.y + s.height / 2})" />`;
      }
      if (s.type === 'circle') {
        return `  <ellipse cx="${s.x + s.width / 2}" cy="${s.y + s.height / 2}" rx="${s.width / 2}" ry="${s.height / 2}" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${s.strokeWidth}" opacity="${s.opacity}" />`;
      }
      if (s.type === 'star') {
        return `  <polygon points="${getStarPoints(s.x + s.width / 2, s.y + s.height / 2, 5, s.width / 2, s.width / 4)}" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${s.strokeWidth}" opacity="${s.opacity}" />`;
      }
      if (s.type === 'path' && s.pathData) {
        return `  <path d="${s.pathData}" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${s.strokeWidth}" opacity="${s.opacity}" />`;
      }
      if (s.type === 'text') {
        return `  <text x="${s.x}" y="${s.y + (s.fontSize || 24)}" font-family="${s.fontFamily || 'system-ui'}" font-size="${s.fontSize || 24}" font-weight="${s.variableFont?.weight || 800}" fill="${s.fill}" letter-spacing="${s.letterSpacing || 2}">${s.text}</text>`;
      }
      return '';
    })
    .join('\n');

  return `<svg viewBox="0 0 ${doc.canvasWidth} ${doc.canvasHeight}" width="${doc.canvasWidth}" height="${doc.canvasHeight}" xmlns="http://www.w3.org/2000/svg">
  <!-- Generated by Creative Suite (Offline-First Engine) -->
  <defs>
    <filter id="shadowFilter">
      <feDropShadow dx="0" dy="6" stdDeviation="8" flood-opacity="0.35"/>
    </filter>
  </defs>
${shapesXml}
</svg>`;
}

/**
 * Renders document to PNG Data-URL using an offscreen HTML5 Canvas.
 */
export async function renderDocumentToRaster(
  doc: UnifiedDocument,
  format: 'image/png' | 'image/webp' = 'image/png',
  scale: number = 1
): Promise<string> {
  const canvas = document.createElement('canvas');
  canvas.width = (doc.canvasWidth || 1200) * scale;
  canvas.height = (doc.canvasHeight || 800) * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Could not get Canvas 2D context');

  ctx.scale(scale, scale);

  // Background
  ctx.fillStyle = '#0a0c12';
  ctx.fillRect(0, 0, doc.canvasWidth, doc.canvasHeight);

  // Render Vector Layers
  for (const s of doc.vectorLayers) {
    ctx.save();
    ctx.globalAlpha = s.opacity ?? 1;

    if (s.type === 'rect') {
      ctx.fillStyle = s.fill;
      ctx.fillRect(s.x, s.y, s.width, s.height);
      if (s.stroke && s.strokeWidth > 0) {
        ctx.strokeStyle = s.stroke;
        ctx.lineWidth = s.strokeWidth;
        ctx.strokeRect(s.x, s.y, s.width, s.height);
      }
    } else if (s.type === 'circle') {
      ctx.beginPath();
      ctx.ellipse(s.x + s.width / 2, s.y + s.height / 2, s.width / 2, s.height / 2, 0, 0, Math.PI * 2);
      ctx.fillStyle = s.fill;
      ctx.fill();
      if (s.stroke && s.strokeWidth > 0) {
        ctx.strokeStyle = s.stroke;
        ctx.lineWidth = s.strokeWidth;
        ctx.stroke();
      }
    } else if (s.type === 'shield') {
      const cx = s.x + s.width / 2;
      const cy = s.y + s.height;
      ctx.beginPath();
      ctx.moveTo(s.x, s.y);
      ctx.lineTo(s.x + s.width, s.y);
      ctx.bezierCurveTo(s.x + s.width, s.y + s.height * 0.65, cx, cy, cx, cy);
      ctx.bezierCurveTo(cx, cy, s.x, s.y + s.height * 0.65, s.x, s.y);
      ctx.closePath();
      ctx.fillStyle = s.fill;
      ctx.fill();
      if (s.stroke && s.strokeWidth > 0) {
        ctx.strokeStyle = s.stroke;
        ctx.lineWidth = s.strokeWidth;
        ctx.stroke();
      }
    } else if (s.type === 'star') {
      const cx = s.x + s.width / 2;
      const cy = s.y + s.height / 2;
      const outerR = s.width / 2;
      const innerR = s.width / 4;
      let rot = (Math.PI / 2) * 3;
      const step = Math.PI / 5;
      ctx.beginPath();
      for (let i = 0; i < 5; i++) {
        const x = cx + Math.cos(rot) * outerR;
        const y = cy + Math.sin(rot) * outerR;
        if (i === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
        rot += step;
        ctx.lineTo(cx + Math.cos(rot) * innerR, cy + Math.sin(rot) * innerR);
        rot += step;
      }
      ctx.closePath();
      ctx.fillStyle = s.fill;
      ctx.fill();
      if (s.stroke && s.strokeWidth > 0) {
        ctx.strokeStyle = s.stroke;
        ctx.lineWidth = s.strokeWidth;
        ctx.stroke();
      }
    } else if (s.type === 'path' && s.pathData) {
      try {
        const path2d = new Path2D(s.pathData);
        ctx.fillStyle = s.fill;
        ctx.fill(path2d);
        if (s.stroke && s.strokeWidth > 0) {
          ctx.strokeStyle = s.stroke;
          ctx.lineWidth = s.strokeWidth;
          ctx.stroke(path2d);
        }
      } catch (err) {
        console.warn('Canvas path render failed', err);
      }
    } else if (s.type === 'text') {
      ctx.fillStyle = s.fill;
      ctx.font = `${s.variableFont?.weight || 800} ${s.fontSize || 24}px system-ui, sans-serif`;
      ctx.fillText(s.text || '', s.x, s.y + (s.fontSize || 24));
    }
    ctx.restore();
  }

  return canvas.toDataURL(format);
}

/**
 * Downloads string content as a local file without any network requests.
 */
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function getStarPoints(cx: number, cy: number, spikes: number, outerRadius: number, innerRadius: number) {
  let rot = (Math.PI / 2) * 3;
  let x = cx;
  let y = cy;
  let step = Math.PI / spikes;
  let points = '';
  for (let i = 0; i < spikes; i++) {
    x = cx + Math.cos(rot) * outerRadius;
    y = cy + Math.sin(rot) * outerRadius;
    points += `${x},${y} `;
    rot += step;
    x = cx + Math.cos(rot) * innerRadius;
    y = cy + Math.sin(rot) * innerRadius;
    points += `${x},${y} `;
    rot += step;
  }
  return points.trim();
}
